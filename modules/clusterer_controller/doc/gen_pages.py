#!/usr/bin/env python3
"""
gen_pages.py <admin-guide README>  - regenerate the doc/ pages that come from
the module's admin guide.

The module README on the PR branch (OpenSIPS#4074) is the admin guide that
goes upstream.  On this branch it is split into pages: every section of the
admin guide goes to the page ROUTE names, one heading level up, and links
between sections point to the page each section lands on.  The quick start
(README.md) and the when-to-use, protocol, failure-detection and measurements
pages are written by hand here and left alone.  A section the admin guide
gains that ROUTE does not name stops the script, so nothing is dropped.

Run from modules/clusterer_controller:

    git show <pr-branch>:modules/clusterer_controller/README.md > /tmp/guide.md
    python3 doc/gen_pages.py /tmp/guide.md
"""
import glob
import os
import re
import sys

TITLES = {
    'how-it-works.md': 'How it works',
    'installation.md': 'Installation',
    'parameters.md':   'Parameters',
    'statistics.md':   'Statistics',
    'mi.md':           'MI commands',
    'scripting.md':    'Scripting',
    'deployment.md':   'Deployment',
    'ha-tests.md':     'HA behaviour tests',
    'testing.md':      'Tests',
}
ROUTE = {   # admin-guide heading -> page (None: dropped here)
    '## Admin Guide': None,
    '### Overview': 'how-it-works.md',
    '### Discovery Protocol': 'how-it-works.md',
    '### Cluster identity': 'how-it-works.md',
    '### Master Election': 'how-it-works.md',
    '### Security Architecture': 'how-it-works.md',
    '### Dependencies': 'installation.md',
    '### Building the Module': 'installation.md',
    '### Exported Parameters': 'parameters.md',
    '### Exported Statistics': 'statistics.md',
    '### Exported MI Functions': 'mi.md',
    '### Exported Pseudo-Variables': 'scripting.md',
    '### Exported Functions': 'scripting.md',
    '### Exported Events': 'scripting.md',
    '### Messaging Between Nodes': 'scripting.md',
    '### Multiple Clusters': 'deployment.md',
    '### Hybrid Topologies (native + controller clusters)': 'deployment.md',
    '### Configuration Example': 'deployment.md',
    '### Upgrading': 'deployment.md',
    '### Limitations': 'deployment.md',
    '### Planned Features': 'deployment.md',
    '## HA Behaviour Tests': 'ha-tests.md',   # its ### headings stay inside it
    '### Automated tests': 'testing.md',
    '### License': None,                      # README.md carries it
}
MARK = ('<!-- generated by doc/gen_pages.py from the module README on the PR '
        'branch - edit that README, not this page -->')


def slug(t):
    t = re.sub(r'[^\w\- ]', '', t.strip().lower())
    return t.replace(' ', '-')


def headings(text):
    out, fence = [], False
    for l in text.split('\n'):
        if l.startswith('```'):
            fence = not fence
        if not fence and re.match(r'^#{1,6} ', l):
            out.append(l)
    return out


def main(guide):
    src = open(guide).read()
    body = src[src.index('---', 3) + 3:] if src.startswith('---') else src
    pages = {p: [] for p in TITLES}
    cur, block, fence = None, None, False
    for l in body.split('\n'):
        if l.startswith('```'):
            fence = not fence
        if l.strip() == '<!-- CONTRIBUTORS -->':
            continue
        if not fence and re.match(r'^#{2,3} ', l):
            if l in ROUTE:
                block, cur = l, ROUTE[l]
                if cur is None or l == '## HA Behaviour Tests':
                    continue                  # the page title stands for it
                pages[cur].append('#' * (len(l) - len(l.lstrip('#')) - 1) + l.lstrip('#'))
                continue
            if block != '## HA Behaviour Tests' or not l.startswith('### '):
                sys.exit('gen_pages.py: no page for the section "%s" - add it to ROUTE' % l)
        if cur is None:
            continue
        if not fence and re.match(r'^#{3,6} ', l):
            n = len(l) - len(l.lstrip('#'))
            l = '#' * (n - 1) + l[n:]
        pages[cur].append(l)

    # every anchor on every page, generated or written here
    anchors = {}
    for p, ls in pages.items():
        for h in headings('\n'.join(ls)):
            anchors.setdefault(slug(h.lstrip('#')), p)
    for f in glob.glob('doc/*.md'):
        p = os.path.basename(f)
        if p not in TITLES:
            for h in headings(open(f).read()):
                anchors.setdefault(slug(h.lstrip('#')), p)
    for h in headings(open('README.md').read()):
        anchors.setdefault(slug(h.lstrip('#')), '../README.md')

    missing = []

    def relink(text, here):
        def rep(m):
            p = anchors.get(m.group(1))
            if p is None:
                missing.append((here, m.group(1)))
                return m.group(0)
            return '](#%s)' % m.group(1) if p == here else '](%s#%s)' % (p, m.group(1))
        return re.sub(r'\]\(#([^)]+)\)', rep, text)

    for p, title in TITLES.items():
        text = '\n'.join(pages[p]).strip('\n')
        if not text:
            if os.path.exists('doc/' + p):
                os.remove('doc/' + p)
            continue
        open('doc/' + p, 'w').write('[clusterer_controller](../README.md) / %s\n\n# %s\n\n%s\n\n%s\n'
                                    % (title, title, MARK, relink(text, p)))
    if missing:
        sys.exit('gen_pages.py: links to sections no page has: %s' % missing)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
